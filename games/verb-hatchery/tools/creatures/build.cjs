// node build.cjs [id …]   — builds the creature collection from roster.json.
//   1. Blender (build.py): source model → raw GLB + icon + silhouette, one Blender run for all
//   2. optimize.cjs: raw GLB → small GLB in ../../assets/creatures/
//   3. writes ../../assets/creatures/creatures.json (the manifest the game reads)
// With ids: rebuilds only those (the manifest keeps the other entries).
// Env: BLENDER=/path/to/blender(.exe)   (default: Blender 4.5 on Windows, called from WSL)
const fs = require('fs'), path = require('path'), { spawnSync, execFileSync } = require('child_process');
const { optimize } = require('./optimize.cjs');

const HERE = __dirname, OUT = path.resolve(HERE, '../../assets/creatures'), TMP = path.join(HERE, '.tmp');
const roster = JSON.parse(fs.readFileSync(path.join(HERE, 'roster.json'), 'utf8'));
const BLENDER = process.env.BLENDER || '/mnt/c/Program Files/Blender Foundation/Blender 4.5/blender.exe';
const WIN = /\.exe$/i.test(BLENDER);
const P = (p) => (WIN ? execFileSync('wslpath', ['-w', p]).toString().trim() : p); // path as Blender sees it
const only = process.argv.slice(2);

fs.mkdirSync(path.join(OUT, 'icons'), { recursive: true }); fs.mkdirSync(TMP, { recursive: true });
const list = roster.creatures.filter((c) => !only.length || only.includes(c.id));
const ids = roster.creatures.map((c) => c.id);
if (new Set(ids).size !== ids.length) throw new Error('duplicate id in roster.json');

const jobs = list.map((c) => {
  const pack = roster.packs[c.pack]; if (!pack) throw new Error(`${c.id}: unknown pack ${c.pack}`);
  const dir = path.join(roster.assetsRoot, pack.dir), src = path.join(dir, c.src + pack.ext);
  if (!fs.existsSync(src)) throw new Error(`${c.id}: missing source ${src}`);
  const job = { id: c.id, src: P(src), out_glb: P(path.join(TMP, c.id + '.glb')),
    out_icon: P(path.join(OUT, 'icons', c.id + '.webp')), out_sil: P(path.join(OUT, 'icons', c.id + '_s.webp')),
    clips: { ...(pack.clips || {}), ...(c.clips || {}) } };
  const tex = c.texture || pack.texture;
  if (tex) job.texture = P(path.resolve(dir, tex.replace('{src}', c.src)));
  for (const k of ['yaw', 'pitch', 'max_tris', 'tex', 'icon_az', 'icon_el', 'icon_frame', 'frame_step', 'drop_meshes']) if (c[k] !== undefined) job[k] = c[k];
  return job;
});
const jobsFile = path.join(TMP, 'jobs.json'), reportFile = path.join(TMP, 'report.json');
fs.writeFileSync(jobsFile, JSON.stringify({ jobs, report: P(reportFile) }, null, 1));
console.log(`Blender: ${jobs.length} creatures …`);
const r = spawnSync(BLENDER, ['-b', '--factory-startup', '-P', P(path.join(HERE, 'build.py')), '--', P(jobsFile)], { encoding: 'utf8', maxBuffer: 1 << 28 });
fs.writeFileSync(path.join(TMP, 'blender.log'), (r.stdout || '') + (r.stderr || ''));
const report = Object.fromEntries(JSON.parse(fs.readFileSync(reportFile, 'utf8')).map((x) => [x.id, x]));

const manifestFile = path.join(OUT, 'creatures.json');
const old = fs.existsSync(manifestFile) ? Object.fromEntries(JSON.parse(fs.readFileSync(manifestFile, 'utf8')).creatures.map((c) => [c.id, c])) : {};
const HOVER = { walk: 0, swim: 0.25, fly: 0.3 };
let failed = 0;
for (const c of list) {
  const rep = report[c.id];
  if (!rep || !rep.ok) { console.log(`FAILED ${c.id}: ${rep ? rep.error : 'no report (see .tmp/blender.log)'}`); failed++; continue; }
  const { glb, stats } = optimize(fs.readFileSync(path.join(TMP, c.id + '.glb')));
  fs.writeFileSync(path.join(OUT, c.id + '.glb'), glb);
  const pack = roster.packs[c.pack], has = stats.clips, move = c.move || 'walk';
  const clips = { idle: 'idle', walk: has.includes('walk') ? 'walk' : (c.walk && has.includes(c.walk) ? c.walk : 'idle') };
  for (const k of ['jump', 'eat', 'fun']) if (has.includes(k)) clips[k] = k;
  old[c.id] = {
    id: c.id, name: c.name, zone: c.zone, rarity: c.rarity, kind: c.monster ? 'monster' : 'animal',
    file: c.id + '.glb', icon: `icons/${c.id}.webp`, silhouette: `icons/${c.id}_s.webp`,
    clips, sourceClips: rep.clips, scale: c.scale, move, hover: c.hover ?? HOVER[move], size: rep.size,
    tris: stats.tris, bytes: stats.bytes, pack: pack.name, author: pack.author, licence: pack.licence, source: pack.url,
  };
  console.log(`${c.id.padEnd(16)} ${String(rep.src_tris).padStart(5)} → ${String(stats.tris).padStart(4)} tris  ${String(Math.round(stats.bytes / 1024)).padStart(4)} KB  clips ${has.join(',')}`);
}
const creatures = roster.creatures.map((c) => old[c.id]).filter(Boolean);
fs.writeFileSync(manifestFile, JSON.stringify({
  note: 'Generated by tools/creatures/build.cjs from roster.json. Do not edit by hand.',
  model: 'Each GLB: root node "creature", looks at +Z, stands on y = 0, longest side 1.0. size = [width, height, length] of that model; scale = suggested height in metres in a pen (factor = scale / size[1]). clips maps the standard names to clip names in the file (walk falls back to jump or idle). hover = suggested height above the ground for swimmers / flyers (metres). Every creature may also hatch as a golden version (done in code).',
  zones: ['meadow', 'forest', 'beach', 'volcano'], rarities: ['common', 'uncommon', 'rare', 'epic', 'legendary'],
  creatures }, null, 1).replace(/\[\n\s+([-\d.]+),\n\s+([-\d.]+),\n\s+([-\d.]+)\n\s+\]/g, '[$1, $2, $3]'));
const total = creatures.reduce((s, c) => s + c.bytes, 0);
console.log(`${creatures.length} creatures in the manifest, GLBs ${(total / 1048576).toFixed(2)} MB${failed ? `, ${failed} FAILED` : ''}`);
process.exit(failed ? 1 : 0);
