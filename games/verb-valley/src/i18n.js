const STRINGS = { en: EN, de: DE, es: ES };

export const LANG = (() => {
  try {
    const p = new URLSearchParams(location.search).get('lang');
    if (p && STRINGS[p]) { localStorage.setItem(KEY, p); return p; }
    const s = localStorage.getItem(KEY);
    if (s && STRINGS[s]) return s;
  } catch (e) { /* storage blocked */ }
  const nav = ((navigator.language || 'en').slice(0, 2)).toLowerCase();
  return STRINGS[nav] ? nav : 'en';
})();

/** Translate a key; template keys take args. Falls back to English. */
export function t(key, ...args) {
  const v = STRINGS[LANG][key] ?? EN[key];
  if (v == null) return key;
  return typeof v === 'function' ? v(...args) : v;
}

/** Display name of a crop or item id (crop.* first, then item.*). */
export function nameOf(id) {
  const v = STRINGS[LANG]['crop.' + id] ?? STRINGS[LANG]['item.' + id] ?? EN['crop.' + id] ?? EN['item.' + id] ?? id;
  return v;
}

/** Same, capitalised for the start of a line (Spanish names are lower-case). */
export function NameOf(id) {
  const n = nameOf(id);
  return n.charAt(0).toUpperCase() + n.slice(1);
}

/** Swap every static data-i18n node once at boot. */
export function applyStatic() {
  document.querySelectorAll('[data-i18n]').forEach((el) => { el.innerHTML = t(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); });
  document.documentElement.lang = LANG;
}
